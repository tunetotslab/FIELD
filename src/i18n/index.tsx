const dictionaries: Record<Locale, Record<Key, string>> = {
  en,
  ru,
  hy,
  "zh-TW": zh,
};
const Context = createContext<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: Key) => string;
}>({ locale: "en", setLocale: () => {}, t: (key) => en[key] });
export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setState] = useState<Locale>(
    () => (localStorage.getItem("field-locale") as Locale) || "en",
  );
  const value = useMemo(
    () => ({
      locale,
      setLocale: (next: Locale) => {
        localStorage.setItem("field-locale", next);
        document.documentElement.lang = next;
        setState(next);
      },
      t: (key: Key) => dictionaries[locale][key],
    }),
    [locale],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}
export const useI18n = () => useContext(Context);
